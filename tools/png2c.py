#!/usr/bin/env python3
"""
png2c.py - convert the brick PNGs into C source files for SGI-L2-GUI.

Runs on the development host (needs Python 3 + Pillow). The generated
files in src/img/ are committed to the repository, so building on IRIX
only needs MIPSpro - no libpng, no SGUG.

Each image is:
  1. scaled to BRICK_WIDTH pixels wide (aspect preserved),
  2. composited over the rack background colour (flattens alpha),
  3. quantised to a 256 colour palette (median cut, no dither),
  4. PackBits RLE compressed (same scheme as Apple/TIFF PackBits):
       n = 0..127   -> copy the next n+1 bytes literally
       n = 129..255 -> repeat the next byte 257-n times
       n = 128      -> no-op

Usage: tools/png2c.py [res/bricks] [src/img]
"""
import os
import sys

from PIL import Image

BRICK_WIDTH = 560
RACK_BG = (40, 40, 40)  # keep in sync with RACK_BG_* in src/skins.h

# png file name -> C symbol suffix
IMAGES = [
    ("O300.png", "o300"),
    ("O350.png", "o350"),
    ("tezro.png", "tezro"),
    ("a350-yellow.png", "a350_yellow"),
    ("a350-grey.png", "a350_grey"),
    ("a3000.png", "a3000"),
    ("a3000ix.png", "a3000ix"),
    ("nl4r.png", "nl4r"),
    ("router.png", "router"),
    ("router-altix.png", "router_altix"),
]


def packbits(data):
    out = bytearray()
    i = 0
    n = len(data)
    while i < n:
        j = i
        while j < n and j - i < 128 and data[j] == data[i]:
            j += 1
        if j - i >= 3:
            out.append(257 - (j - i))
            out.append(data[i])
            i = j
            continue
        j = i
        while j < n and j - i < 128:
            if j + 2 < n and data[j] == data[j + 1] == data[j + 2]:
                break
            j += 1
        out.append(j - i - 1)
        out += data[i:j]
        i = j
    return bytes(out)


def unpackbits(data, size):
    out = bytearray()
    i = 0
    while len(out) < size:
        n = data[i]
        i += 1
        if n < 128:
            out += data[i:i + n + 1]
            i += n + 1
        elif n > 128:
            out += bytes([data[i]]) * (257 - n)
            i += 1
    return bytes(out)


def c_bytes(data, per_line=20):
    lines = []
    for k in range(0, len(data), per_line):
        lines.append("  " + ",".join(str(b) for b in data[k:k + per_line]) + ",")
    return "\n".join(lines)


def convert(src, sym, outdir):
    im = Image.open(src).convert("RGBA")
    h = int(round(im.height * BRICK_WIDTH / float(im.width)))
    im = im.resize((BRICK_WIDTH, h), Image.LANCZOS)
    bg = Image.new("RGBA", im.size, RACK_BG + (255,))
    bg.alpha_composite(im)
    q = bg.convert("RGB").quantize(256, method=Image.MEDIANCUT, dither=Image.NONE)
    pal = q.getpalette()[:768]
    pal += [0] * (768 - len(pal))
    idx = q.tobytes()
    packed = packbits(idx)
    assert unpackbits(packed, len(idx)) == idx

    path = os.path.join(outdir, "img_%s.c" % sym)
    with open(path, "w") as f:
        f.write("/* GENERATED by tools/png2c.py from %s - do not edit */\n"
                % os.path.basename(src))
        f.write('#include "../image.h"\n\n')
        f.write("static const unsigned char pal[768] = {\n%s\n};\n\n" % c_bytes(pal))
        f.write("static const unsigned char data[%d] = {\n%s\n};\n\n"
                % (len(packed), c_bytes(packed)))
        f.write("const EmbImage img_%s = { %d, %d, pal, %d, data };\n"
                % (sym, BRICK_WIDTH, h, len(packed)))
    print("%-18s -> %s (%dx%d, %d bytes packed)" % (os.path.basename(src), path,
                                                     BRICK_WIDTH, h, len(packed)))


def main():
    srcdir = sys.argv[1] if len(sys.argv) > 1 else "res/bricks"
    outdir = sys.argv[2] if len(sys.argv) > 2 else "src/img"
    if not os.path.isdir(outdir):
        os.makedirs(outdir)
    for fname, sym in IMAGES:
        convert(os.path.join(srcdir, fname), sym, outdir)
    with open(os.path.join(outdir, "images.h"), "w") as f:
        f.write("/* GENERATED by tools/png2c.py - do not edit */\n")
        f.write("#ifndef SGIL2_IMAGES_H\n#define SGIL2_IMAGES_H\n")
        f.write('#include "../image.h"\n')
        for _, sym in IMAGES:
            f.write("extern const EmbImage img_%s;\n" % sym)
        f.write("#endif\n")


if __name__ == "__main__":
    main()
